create table if not exists public.arena_players (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Guest' check (char_length(display_name) between 2 and 16),
  xp integer not null default 0 check (xp >= 0),
  streak integer not null default 0 check (streak >= 0),
  last_daily date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.arena_scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mode text not null check (mode in ('daily','football','tech','gaming','general','riddles')),
  score integer not null check (score >= 0),
  correct_count integer not null check (correct_count >= 0),
  total_questions integer not null check (total_questions between 1 and 20),
  played_on date not null default current_date,
  created_at timestamptz not null default now(),
  check (correct_count <= total_questions),
  check (score <= total_questions * 100)
);
create index if not exists arena_scores_user_idx on public.arena_scores(user_id, created_at desc);
create index if not exists arena_scores_mode_idx on public.arena_scores(mode, score desc, created_at desc);
create unique index if not exists arena_daily_once_idx on public.arena_scores(user_id, played_on) where mode='daily';

create table if not exists public.arena_poll_votes (
  poll_key text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  choice text not null check (choice in ('skill','strategy')),
  created_at timestamptz not null default now(),
  primary key (poll_key, user_id)
);

create table if not exists public.arena_rooms (
  code text primary key check (char_length(code) = 6),
  host_user uuid not null references auth.users(id) on delete cascade,
  mode text not null check (mode in ('daily','football','tech','gaming','general','riddles')),
  target_score integer not null check (target_score between 0 and 5000),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '7 days')
);
create index if not exists arena_rooms_expiry_idx on public.arena_rooms(expires_at);

create table if not exists public.arena_room_scores (
  room_code text not null references public.arena_rooms(code) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 2 and 16),
  score integer not null check (score between 0 and 5000),
  correct_count integer not null default 0 check (correct_count >= 0),
  total_questions integer not null default 1 check (total_questions between 1 and 20),
  updated_at timestamptz not null default now(),
  primary key (room_code, user_id),
  check (correct_count <= total_questions)
);

alter table public.arena_players enable row level security;
